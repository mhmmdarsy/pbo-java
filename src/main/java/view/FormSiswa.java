    private void tampilData() {
        model = new DefaultTableModel(new String[]{"ID", "Nama", "Kelas"}, 0);
        tblSiswa.setModel(model);
        try (Connection conn = DatabaseConn.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT * FROM siswa")) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("nama"),
                    rs.getString("kelas")
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data: " + ex.getMessage());
        }
    }

    private void resetForm() {
        txtNama.setText("");
        txtKelas.setText("");
    }

    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
        String nama = txtNama.getText().trim();
        String kelas = txtKelas.getText().trim();
        
//      validasi input
        if (nama.isEmpty() || kelas.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Nama dan Kelas tidak boleh kosong!", 
                "Peringatan", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        try (Connection conn = DatabaseConn.getConnection()) {
            Siswa s = new Siswa(txtNama.getText(), txtKelas.getText());
            String sql = "INSERT INTO siswa (nama, kelas) VALUES (?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, s.getNama());
            pst.setString(2, s.getKelas());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan!");
            tampilData();
            resetForm();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan data: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int row = tblSiswa.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data yang ingin diubah!");
            return;
        }

        int id = (int) tblSiswa.getValueAt(row, 0); // ambil ID dari kolom pertama
        try (Connection conn = DatabaseConn.getConnection()) {
            String sql = "UPDATE siswa SET nama=?, kelas=? WHERE id=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtNama.getText());
            pst.setString(2, txtKelas.getText());
            pst.setInt(3, id);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data berhasil diubah!");
            tampilData();
            resetForm();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnEditActionPerformed

